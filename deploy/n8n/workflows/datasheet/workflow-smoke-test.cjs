'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const workflow = JSON.parse(fs.readFileSync(path.join(__dirname,'pv-wiki-datasheet-agent.json'),'utf8'));
const nodes = Object.fromEntries(workflow.nodes.map(node=>[node.name,node]));
function run(name,input,refs={}) {
  const values=Array.isArray(input)?input:[input];
  const $input={first:()=>({json:values[0]}),all:()=>values.map(json=>({json}))};
  const $=name=>{
    const data=refs[name];
    if (!data) throw new Error('Missing reference '+name);
    return {first:()=>({json:data}),last:()=>({json:data}),item:{json:data}};
  };
  return new Function('$input','$',nodes[name].parameters.jsCode)($input,$);
}
for (const node of workflow.nodes.filter(n=>n.type==='n8n-nodes-base.code')) {
  new Function('$input','$',node.parameters.jsCode);
}
const config={vision_enabled:true,max_repair_attempts:3,max_research_rounds:3};
const selected={product_id:'SKU',source_hash:'snapshot',revision:'old-revision',product:{brand_code:'MAKER'}};
const pdf={document_id:'a'.repeat(64),artifact_sha256:'a'.repeat(64),url:'https://maker.example/dl',official_page_url:'https://maker.example/model',content:'unaltered PDF text',receipt:{signed:true},page_count:3,parameter_rows:[]};
const context={selected,pdf,discovery:{target_model:'M-500',manufacturer:'Maker',verification_reason:'Official product download'},visual_reviews:[],research_round:1,repair_attempt:0};
const pages=run('Prepare Page Reviews',context,{'Configuration':config});
assert.equal(pages.length,3);
assert.deepEqual(pages[2].json.pages,[1,2,3]);
assert.equal(pages[0].json.restart_page_loop,true);
for(const requested of [[999],['2'],[0,-1,4,null],[]]){
const fallback=run('Prepare Page Reviews',{...context,review_pages:requested},{'Configuration':config});
assert.deepEqual(fallback.map(item=>item.json.page),[1,2,3]);
assert.equal(fallback[0].json.restart_page_loop,true);
}
const partial=run('Prepare Page Reviews',{...context,review_pages:[999,2,2,'3']},{'Configuration':config});
assert.deepEqual(partial.map(item=>item.json.page),[2]);
assert.throws(()=>run('Prepare Page Reviews',{...context,pdf:{...pdf,page_count:0}},{'Configuration':config}),/Invalid PDF page count/);
const task=pages[2].json;
const images=[1,2,3].map(page=>({page,data:Buffer.from('PNG'+page).toString('base64'),mime_type:'image/png'}));
const attached=run('Attach Real Images',{images,receipt:{signed_view:true}},{'Review Pages Serially':task})[0];
assert.equal(attached.json.has_images,true);
assert.equal(Buffer.from(attached.binary.page.data,'base64').toString(),'PNG3');
assert.equal(Buffer.from(attached.binary.previous.data,'base64').toString(),'PNG2');
assert.equal(attached.binary.page.mimeType,'image/png');
const missing=run('Attach Real Images',{ok:false,error:'render_failed'},{'Review Pages Serially':task})[0];
assert.equal(missing.json.has_images,false);
const disabled=run('Record Text Only Page',{...task,vision_enabled:false})[0].json;
assert.equal(disabled.status,'unavailable');
const visualFailure=run('Capture Visual Review',{error:'unsupported image input'},{'Attach Real Images':attached.json})[0].json;
assert.equal(visualFailure.status,'failed');
assert.equal(visualFailure.receipt,null);
const visualSuccess=run('Capture Visual Review',{text:JSON.stringify({parameters:[{value:'500'}],omissions:[]})},{'Attach Real Images':attached.json})[0].json;
assert.equal(visualSuccess.status,'reviewed');
assert.deepEqual(visualSuccess.receipt,{signed_view:true});
const parameters=Array.from({length:350},(_,i)=>({parameter_id:'p'+String(i+1).padStart(3,'0'),source_label:'Parameter '+i,value:'±500–600',unit:'V',model:'M-500',scope:'model',page:2,status:'confirmed',source_kind:'parser'}));
const candidate=run('Read Candidate',{output:JSON.stringify({decision:{parameters}})},{'Compose Input':context,'Configuration':config})[0].json;
assert.equal(candidate.candidate_ready,true);
assert.equal(candidate.decision.parameters.length,350);
assert.equal(candidate.decision.expected_revision,'old-revision');
assert.equal(candidate.decision.visual_review.status,'failed');
assert.equal(candidate.evidence_documents[0].content,pdf.content);
assert.deepEqual(candidate.evidence_documents[0].receipt,pdf.receipt);
const enrich=run('Merge Optional Enrichment',{error:'model_timeout'},{'Read Self Review':candidate})[0].json;
assert.equal(enrich.decision.parameters.length,350);
assert.deepEqual(enrich.decision.parameters,candidate.decision.parameters);
const invalid=run('Read Validation',{ok:true,valid:false,errors:['wrong column']},{'Merge Optional Enrichment':enrich})[0].json;
assert.equal(invalid.validated,false);assert.equal(invalid.next_action,'revise');
assert.match(invalid.feedback,/wrong column/);
const transport=run('Read Validation',{error:'session expired'},{'Merge Optional Enrichment':enrich})[0].json;
assert.equal(transport.next_action,'stop');
const retry=run('Prepare Retry',{...invalid,repair_attempt:2},{'Configuration':config})[0].json;
assert.equal(retry.retry_allowed,true);assert.equal(retry.repair_attempt,3);
const exhausted=run('Prepare Retry',retry,{'Configuration':config})[0].json;
assert.equal(exhausted.retry_allowed,false);
const research=run('Prepare Retry',{...context,next_action:'search',feedback:'no official link'},{'Configuration':config})[0].json;
assert.equal(research.needs_search,true);assert.equal(research.research_round,2);
const view=run('Prepare Retry',{...context,next_action:'view',review_pages:[2],review_region:[0.1,0.2,0.9,0.8]},{'Configuration':config})[0].json;
assert.equal(view.needs_view,true);
assert.deepEqual(run('Prepare Page Reviews',view,{'Configuration':config})[0].json.region,[0.1,0.2,0.9,0.8]);
const saved=run('Read Save Result',{ok:true,created:true},{'Read Validation':invalid})[0].json;
assert.equal(saved.saved,true);
const failedSave=run('Read Save Result',{ok:false,code:'validation_failed',error:'stale revision'},{'Read Validation':invalid})[0].json;
assert.equal(failedSave.saved,false);assert.equal(failedSave.next_action,'revise');
const review=run('Read Self Review',{text:JSON.stringify({verdict:'revise',next_action:'view',corrections:['wrong unit'],review_pages:[2]})},{'Read Candidate':candidate})[0].json;
assert.equal(review.review_passed,false);assert.equal(review.next_action,'view');
console.log('n8n workflow data-flow smoke checks passed (binary vision, 350 rows, fallback, correction/search/view loops).');
